"""Per-race statics rewrite used by transform.py.

Mutable statics (the same set Host::Context saves, plus the kart proxy list). On the GPU every race needs its own copy,
so each `s_x` becomes `s_x_ref()`, a reference into the calling race's statics block (kinoko_race_statics(), one
KINOKO_STATIC_SLOT-byte slot per variable). Each class also gets `s_x_init()`, which constructs the variable with its
original initializer, and befriends the generated `kinoko_statics_init()` that calls all of them.
"""

import collections
import os
import re

STATIC_NAMES = ["s_instance", "s_rootList", "s_archiveList", "s_heapList", "s_currentHeap", "s_allocatableHeap",
                "s_heapForCreateScene", "s_heapOptionFlg", "s_rootHeap", "s_initialXRange", "s_initialYRange",
                "s_flamePoleCount", "s_dotProductCache", "s_wanwanMaxPitch", "s_thunderScaleUpAnmChr",
                "s_thunderScaleDownAnmChr", "s_pressScaleUpAnmChr", "s_onInitCallback", "s_onInitCallbackArg",
                "s_baseUpdateRate", "s_proxyList"]
STATIC_USE = re.compile(r'\b(' + "|".join(STATIC_NAMES) + r')\b')
STATIC_DECL = re.compile(r'\bstatic ([^;{}()]*?)\s*(\*?)\s*\b(s_\w+)_ref\(\);')
STATIC_DEF = re.compile(r'^(?P<type>[A-Za-z_][^;{}=\n]*?(?:\n[^;{}=\n]*?)?)\s*(?P<ptr>\*?)\s*'
                        r'(?<![\w:])(?P<name>[A-Za-z_][\w:]*::(?P<var>s_\w+))_ref\(\)'
                        r'\s*(?:=\s*(?P<init>[^;]+))?;', re.M)
NAMESPACE_OPEN = re.compile(r'^namespace ([\w:]+) \{', re.M)
NAMESPACE_CLOSE = re.compile(r'^\} // namespace', re.M)

DEFS = []  # (index, fully qualified class, var, type)
HEADERS = []  # headers declaring those classes (relative to source/), included by kinoko_statics_init.cu
COUNTS = collections.Counter()


def namespace_at(text, pos):
    events = [(m.start(), m.group(1)) for m in NAMESPACE_OPEN.finditer(text, 0, pos)]
    events += [(m.start(), None) for m in NAMESPACE_CLOSE.finditer(text, 0, pos)]
    stack = []
    for _, ns in sorted(events):
        if ns is None:
            if stack:
                stack.pop()
        else:
            stack.append(ns)
    return "::".join(stack)


def rewrite(path, text):
    text = STATIC_USE.sub(lambda m: (COUNTS.update(["static use -> per-race ref"]), m.group(1) + "_ref()")[1], text)
    if path.endswith(".hh"):
        def sub_decl(m):
            COUNTS["static decl"] += 1
            return (f"static {m.group(1)} {m.group(2)}&{m.group(3)}_ref(); static void {m.group(3)}_init(); "
                    f"friend void ::kinoko_statics_init();")
        return STATIC_DECL.sub(sub_decl, text)

    def sub_def(m):
        rel = os.path.relpath(path, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "source"))
        hdr = rel.replace("\\", "/")[:-3] + ".hh"
        if hdr not in HEADERS:
            HEADERS.append(hdr)
        idx = len(DEFS)
        typ = " ".join(m.group("type").split()) + (" *" if m.group("ptr") else "")
        init = m.group("init")
        init = init.strip() if init else None
        ctor = f"{typ}{init}" if init and init.startswith("{") else f"{typ}({init})" if init else f"{typ}{{}}"
        name = m.group("name")
        cls = name[: -len("::" + m.group("var"))]
        ns = namespace_at(text, m.start())
        full = "::" + (ns + "::" if ns else "Kinoko::") + cls
        DEFS.append((idx, full, m.group("var"), typ))
        COUNTS["static def"] += 1
        return (f"{typ} &{name}_ref() {{\n"
                f"    static_assert(sizeof({typ}) <= KINOKO_STATIC_SLOT);\n"
                f"    return *reinterpret_cast<{typ} *>(kinoko_race_statics() + {idx} * KINOKO_STATIC_SLOT);\n"
                f"}}\n"
                f"void {name}_init() {{\n"
                f"    new (&{name}_ref()) {ctor};\n"
                f"}}")

    return STATIC_DEF.sub(sub_def, text)


def write_init(out_dir):
    lines = ["// Generated by transform.py: constructs every per-race static in the calling race's statics block.",
             "#include <kinoko_gpu_prelude.h>"] + [f"#include <{h}>" for h in HEADERS] + [
             f"constexpr int KINOKO_STATIC_COUNT = {len(DEFS)};",
             'extern "C" void kinoko_statics_init() {']
    lines += [f"    {full}::{var}_init(); // slot {i}: {typ}" for i, full, var, typ in DEFS]
    lines += ["}", ""]
    path = os.path.join(out_dir, "kinoko_statics_init.cu")
    text = "\n".join(lines)
    if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:  # keep the mtime for build caching
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
